#!/usr/bin/env python3
"""Check the `-c` / `--coordinate` readers: PDB, XYZ and CSV.

usage: check.py <path-to-nerdss> [path-to-nerdss_mpi] [work-dir]

Model: P, Q and Longname, one interface each 0.5 nm from the COM, with the
reaction P(p)+Q(q).  nItr = 1, so a run is only the setup, and what it leaves
in DATA/initial_crds.xyz is the whole result.

A run without -c and a run with -c use the same RNG stream up to the moment
the coordinate file is read, so a reference run gives every random position,
and the file-placed molecules are the only ones that differ afterwards.  The
same placements written as PDB, XYZ, CSV with a header and CSV without one
must therefore leave byte-identical initial_crds.xyz files, and that is the
main check.  The rest exercises the detection rules and the error paths.

With a nerdss_mpi path the formats are also run at np=1 and np=2.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

NERDSS = Path(sys.argv[1]).resolve()
MPI = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 and sys.argv[2] else None
HERE = Path(__file__).resolve().parent
MODEL = HERE / "model"
RUNS = Path(sys.argv[3]).resolve() if len(sys.argv) > 3 else Path(tempfile.mkdtemp(prefix="coordfmt_"))

BOX, NP, NQ, NL, SIGMA, SEED = 200, 5, 5, 2, 1, 7
failures = []


def check(cond, msg):
    print(("  PASS  " if cond else "  FAIL  ") + msg)
    if not cond:
        failures.append(msg)


# --------------------------------------------------------------------- writers
def pdb_text(rows):
    # cols 1-6 ATOM, 13-16 atom name, 18-21 residue (= molecule) name, 31-54 xyz
    out = ["REMARK generated by check.py"]
    for i, (n, (x, y, z)) in enumerate(rows):
        out.append(f"ATOM  {i + 1:5d} {'COM':<4} {n:<4}{'':9}{x:8.3f}{y:8.3f}{z:8.3f}")
    return "\n".join(out) + "\n"


def xyz_text(rows, comment="", count=None, eol="\n"):
    lines = [str(len(rows) if count is None else count), comment]
    lines += [f"{n} {x:.3f} {y:.3f} {z:.3f}" for n, (x, y, z) in rows]
    return eol.join(lines) + eol


def csv_text(rows, header=True, eol="\n", spaces=False):
    lines = ["name,x,y,z"] if header else []
    sep = " , " if spaces else ","
    lines += [sep.join([n, f"{x:.3f}", f"{y:.3f}", f"{z:.3f}"]) for n, (x, y, z) in rows]
    return eol.join(lines) + eol


# ------------------------------------------------------------------------ runs
def run(tag, coord_file=None, coord_text=None, mpi_np=None, seed=SEED):
    d = RUNS / tag
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)
    for f in MODEL.glob("*.mol"):
        shutil.copy(f, d)
    parms = (MODEL / "parms.template").read_text()
    for k, v in {"@BOX@": BOX, "@NP@": NP, "@NQ@": NQ, "@NL@": NL, "@SIGMA@": SIGMA}.items():
        parms = parms.replace(k, str(v))
    (d / "parms.inp").write_text(parms)
    if mpi_np is None:
        cmd = [str(NERDSS), "-f", "parms.inp", "-s", str(seed)]
    else:
        cmd = ["mpirun", "--oversubscribe", "-np", str(mpi_np), str(MPI), "-f", "parms.inp", "-s", str(seed)]
    if coord_file is not None:
        (d / coord_file).write_bytes(coord_text.encode() if isinstance(coord_text, str) else coord_text)
        cmd += ["-c", coord_file]
    p = subprocess.run(cmd, cwd=d, capture_output=True, text=True, timeout=600, stdin=subprocess.DEVNULL)
    (d / "stdout.log").write_text(p.stdout)
    (d / "stderr.log").write_text(p.stderr)
    out = p.stdout
    if mpi_np is not None:  # nerdss_mpi sends its stdout to DATA/output_<rank>.txt
        for f in sorted((d / "DATA").glob("output_*.txt")):
            out += f.read_text()
    xyz = d / "DATA" / "initial_crds.xyz"
    return {"rc": p.returncode, "out": out, "err": p.stderr,
            "xyz": xyz.read_bytes() if xyz.exists() else None, "dir": d}


def molecules(xyz_bytes):
    """[(name, com)] in file order; a COM line then one interface line each."""
    lines = xyz_bytes.decode().splitlines()[2:]
    mols = []
    for com_line in lines[0::2]:
        n, *c = com_line.split()
        mols.append((n, tuple(map(float, c))))
    return mols


def same(a, b, tol=1e-5):
    return all(abs(x - y) <= tol for x, y in zip(a, b))


# ============================================================ 1. equivalence
print("\n1. The same placements as PDB, XYZ, CSV (header) and CSV (no header)")
ref = run("ref")
check(ref["rc"] == 0, "reference run (no -c) exits 0")
# initial_crds.xyz is written in the same centred frame the -c file uses
# (only the PDB output adds +L/2), so file positions come back unchanged.
shift = 0.0
# 3 of 5 P, 2 of 5 Q and both Longname go on the file; the rest stay random.
rows = [("P", (10.0, 20.0, 30.0)), ("P", (-40.0, 5.5, -60.25)), ("P", (0.0, 0.0, 0.0)),
        ("Q", (33.0, -33.0, 12.0)), ("Q", (-70.0, 70.0, -70.0)),
        ("Longname", (50.0, 50.0, 50.0)), ("Longname", (-50.0, -50.0, 50.0))]
rows_pdb = [r for r in rows if r[0] != "Longname"]  # a PDB residue name holds 4 characters

pdb = run("pdb", "coords.pdb", pdb_text(rows_pdb))
xyz = run("xyz", "coords.xyz", xyz_text(rows_pdb))
csvh = run("csv_header", "coords.csv", csv_text(rows_pdb, header=True))
csvn = run("csv_noheader", "coords.csv", csv_text(rows_pdb, header=False))
for r, name in ((pdb, "PDB"), (xyz, "XYZ"), (csvh, "CSV with header"), (csvn, "CSV without header")):
    check(r["rc"] == 0 and r["xyz"] is not None, f"{name} run exits 0")
check(pdb["xyz"] == xyz["xyz"] == csvh["xyz"] == csvn["xyz"],
      "PDB, XYZ, CSV (header) and CSV (no header) leave byte-identical initial_crds.xyz")
check("coordinate file format: PDB (from extension)" in pdb["out"], "PDB format printed, from the extension")
check("coordinate file format: XYZ (from extension)" in xyz["out"], "XYZ format printed, from the extension")
check("coordinate file format: CSV (from extension)" in csvh["out"], "CSV format printed, from the extension")

m0, m1 = molecules(ref["xyz"]), molecules(xyz["xyz"])
placed = {}
for n, c in rows_pdb:
    placed.setdefault(n, []).append(c)
for name, coords in placed.items():
    idx = [k for k, m in enumerate(m1) if m[0] == name]
    for i, c in enumerate(coords):
        want = tuple(v + shift for v in c)
        check(same(m1[idx[i]][1], want), f"{name}#{i} sits at the file position {c}")
    check(all(same(m1[k][1], m0[k][1]) for k in idx[len(coords):]),
          f"the {len(idx) - len(coords)} {name} without a file row keep their reference positions")
check(pdb["xyz"] != ref["xyz"], "the file moved something (differs from the reference)")

print("\n2. XYZ and CSV names are not limited to 4 characters")
xyz_l = run("xyz_long", "coords.xyz", xyz_text(rows))
csv_l = run("csv_long", "coords.csv", csv_text(rows))
check(xyz_l["rc"] == 0 and csv_l["rc"] == 0, "both runs exit 0")
check(xyz_l["xyz"] == csv_l["xyz"], "XYZ and CSV with Longname rows are byte-identical")
ml = molecules(xyz_l["xyz"])
idx = [k for k, m in enumerate(ml) if m[0] == "Longname"]
check(same(ml[idx[0]][1], (50.0, 50.0, 50.0)) and same(ml[idx[1]][1], (-50.0, -50.0, 50.0)),
      "both Longname molecules sit at their file positions")

# ============================================================ 3. detection
print("\n3. Detection: extension case, no extension (content sniffing)")
up = [run("ext_upper_pdb", "COORDS.PDB", pdb_text(rows_pdb)),
      run("ext_upper_xyz", "coords.XYZ", xyz_text(rows_pdb)),
      run("ext_upper_csv", "coords.Csv", csv_text(rows_pdb))]
check(all(r["rc"] == 0 and r["xyz"] == pdb["xyz"] for r in up),
      "upper/mixed-case extensions give the same result")
sn = {"pdb": run("sniff_pdb", "coords_pdb", pdb_text(rows_pdb)),
      "xyz": run("sniff_xyz", "coords_xyz", xyz_text(rows_pdb)),
      "csv": run("sniff_csv", "coords_csv", csv_text(rows_pdb)),
      "csv_noheader": run("sniff_csv_noheader", "coords.dat", csv_text(rows_pdb, header=False))}
check(all(r["rc"] == 0 and r["xyz"] == pdb["xyz"] for r in sn.values()),
      "files with no or an unknown extension are read by content and match")
check("format: PDB (from content)" in sn["pdb"]["out"], "PDB sniffed from an ATOM record")
check("format: XYZ (from content)" in sn["xyz"]["out"], "XYZ sniffed from the integer first line")
check("format: CSV (from content)" in sn["csv"]["out"], "CSV sniffed from the comma-separated first row")
check("format: CSV (from content)" in sn["csv_noheader"]["out"], "headerless CSV (.dat) sniffed as CSV")
# PDB with a HETATM record and REMARK lines only
# A HETATM line is enough to sniff PDB; the reader itself still takes ATOM/COM lines only.
het = run("sniff_hetatm", "coords_het", "HETATM    1  O   HOH     1       0.000   0.000   0.000\n" + pdb_text(rows_pdb))
check(het["rc"] == 0 and "format: PDB (from content)" in het["out"] and het["xyz"] == pdb["xyz"],
      "a HETATM record is sniffed as PDB")
bad = run("sniff_unknown", "coords.txt", "this is not a coordinate file\nnor this\n")
check(bad["rc"] != 0 and "cannot tell the format" in bad["err"], "an undetectable file stops the run with a message")

# ============================================================ 4. edge cases
print("\n4. XYZ and CSV edge cases")
e = run("xyz_comment", "coords.xyz", xyz_text(rows_pdb, comment="any text here"))
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "XYZ with a text comment line matches (empty comment is the base case)")
e = run("xyz_crlf", "coords.xyz", xyz_text(rows_pdb, eol="\r\n"))
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "XYZ with CRLF line endings matches")
e = run("csv_crlf", "coords.csv", csv_text(rows_pdb, eol="\r\n"))
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "CSV with CRLF line endings matches")
e = run("csv_spaces_blank", "coords.csv", "\n" + csv_text(rows_pdb, spaces=True).replace("\n", "\n\n"))
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "CSV with spaces around fields and blank lines matches")
e = run("xyz_trailing_blank", "coords.xyz", xyz_text(rows_pdb) + "\n\n")
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "XYZ with trailing blank lines matches")
e = run("csv_first_row_numeric", "coords.csv", csv_text(rows_pdb, header=False))
check(e["rc"] == 0 and len([m for m in molecules(e["xyz"]) if same(m[1], (10 + shift, 20 + shift, 30 + shift))]) == 1,
      "a CSV whose first row is numeric is not taken as a header (its row is applied)")
e = run("csv_header_only", "coords.csv", "name,x,y,z\n")
check(e["rc"] == 0 and e["xyz"] == ref["xyz"], "a header-only CSV leaves the reference placements")
e = run("csv_unknown_name", "coords.csv", csv_text([("Zed", (1.0, 2.0, 3.0))] + rows_pdb))
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "a row with a molecule name not in the system is skipped")
e = run("xyz_unknown_name", "coords.xyz", xyz_text([("Zed", (1.0, 2.0, 3.0))] + rows_pdb))
check(e["rc"] == 0 and e["xyz"] == pdb["xyz"], "... in XYZ too")
e = run("xyz_more_rows", "coords.xyz", xyz_text(rows_pdb, count=len(rows_pdb) - 1))
fewer = run("xyz_fewer_rows_ref", "coords.xyz", xyz_text(rows_pdb[:-1]))
check(e["rc"] == 0 and "WARNING" in e["out"] and e["xyz"] == fewer["xyz"],
      "XYZ with more rows than line 1 announces: warning, extra rows ignored")
e = run("xyz_fewer_rows", "coords.xyz", xyz_text(rows_pdb, count=len(rows_pdb) + 1))
check(e["rc"] != 0 and "holds only" in e["err"], "XYZ with fewer rows than line 1 announces stops the run")
e = run("xyz_zero", "coords.xyz", "0\n")
check(e["rc"] == 0 and e["xyz"] == ref["xyz"], "an XYZ announcing 0 rows (no comment line) leaves the reference placements")

print("\n5. Malformed rows stop the run with the file name and line number")
bad_xyz = xyz_text(rows_pdb).replace("-40.000 5.500", "-40.000 abc")   # line 4
e = run("xyz_bad_number", "coords.xyz", bad_xyz)
check(e["rc"] != 0 and "coords.xyz, line 4" in e["err"] and "not a number" in e["err"],
      f"XYZ row with a non-number: {e['err'].strip().splitlines()[0] if e['err'] else '(no message)'}")
e = run("xyz_bad_fields", "coords.xyz", xyz_text(rows_pdb).replace("Q 33.000 -33.000 12.000", "Q 33.000 -33.000"))
check(e["rc"] != 0 and "coords.xyz, line 6" in e["err"] and "expected 4 fields" in e["err"],
      "XYZ row with 3 fields: line number reported")
e = run("xyz_bad_count", "coords.xyz", "five\n\n" + "P 1 2 3\n")
check(e["rc"] != 0 and "coords.xyz, line 1" in e["err"], "XYZ whose line 1 is not a whole number")
e = run("csv_bad_number", "coords.csv", csv_text(rows_pdb).replace("-40.000,5.500", "-40.000,5.5x"))  # line 3
check(e["rc"] != 0 and "coords.csv, line 3" in e["err"] and "not a number" in e["err"],
      "CSV row with a numeric prefix ('5.5x') is rejected with its line number")
e = run("csv_bad_fields", "coords.csv", csv_text(rows_pdb) + "Q,1,2\n")
check(e["rc"] != 0 and f"coords.csv, line {len(rows_pdb) + 2}" in e["err"], "CSV row with 3 fields: line number reported")
e = run("csv_empty_name", "coords.csv", csv_text(rows_pdb) + ",1,2,3\n")
check(e["rc"] != 0 and "empty molecule name" in e["err"], "CSV row with an empty name is rejected")
e = run("xyz_header_as_row", "coords.xyz", "2\n\nname x y z\nP 1 2 3\n")
check(e["rc"] != 0 and "line 3" in e["err"], "XYZ has no header detection: a text row is an error")
# -c naming a file that does not exist keeps the old behaviour: a message, no placement.
d = RUNS / "missing_file"
shutil.rmtree(d, ignore_errors=True)
d.mkdir(parents=True)
for f in MODEL.glob("*.mol"):
    shutil.copy(f, d)
shutil.copy(RUNS / "ref" / "parms.inp", d)
p = subprocess.run([str(NERDSS), "-f", "parms.inp", "-s", str(SEED), "-c", "nothere.xyz"], cwd=d,
                   capture_output=True, text=True, stdin=subprocess.DEVNULL)
check(p.returncode == 0 and "Could not open coordinate file" in p.stderr
      and (d / "DATA" / "initial_crds.xyz").read_bytes() == ref["xyz"],
      "a missing file warns and keeps the generated coordinates (unchanged behaviour)")

# ============================================================ 6. MPI
if MPI is not None:
    print("\n6. nerdss_mpi at np=1 and np=2")
    for np_ in (1, 2):
        r = {name: run(f"mpi{np_}_{name}", fn, text, mpi_np=np_) for name, fn, text in (
            ("pdb", "coords.pdb", pdb_text(rows_pdb)),
            ("xyz", "coords.xyz", xyz_text(rows_pdb)),
            ("csv", "coords.csv", csv_text(rows_pdb)),
            ("csv_noheader", "coords.csv", csv_text(rows_pdb, header=False)))}
        check(all(v["rc"] == 0 and v["xyz"] is not None for v in r.values()), f"np={np_}: all four formats exit 0")
        check(len({v["xyz"] for v in r.values()}) == 1, f"np={np_}: the four formats leave byte-identical initial_crds.xyz")
        check(all("coordinate file format:" in v["out"] for v in r.values()), f"np={np_}: the format is printed")
        m = molecules(r["xyz"]["xyz"])
        idx = [k for k, mm in enumerate(m) if mm[0] == "P"]
        check(same(m[idx[0]][1], (10 + shift, 20 + shift, 30 + shift)), f"np={np_}: P#0 sits at the file position")
        e = run(f"mpi{np_}_bad", "coords.csv", csv_text(rows_pdb).replace("-40.000,5.500", "-40.000,5.5x"), mpi_np=np_)
        check(e["rc"] != 0 and "coords.csv, line 3" in e["err"], f"np={np_}: a malformed row stops the run with its line number")

print(f"\nruns in {RUNS}")
print("ALL PASS" if not failures else f"{len(failures)} FAILURE(S)")
sys.exit(1 if failures else 0)
